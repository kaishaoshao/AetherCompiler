"""
Frontend Component: PyTorch 2.0 FX Graph Importer.

Bridges the PyTorch ecosystem with Zen-NPU by converting PyTorch FX Graphs
(generated by `torch.compile`, `torch.export`, or `torch.fx.symbolic_trace`)
into native `frontend.Graph` representations.

Also supports a standalone, zero-dependency JSON schema representation of FX Graphs,
allowing models exported on a machine with PyTorch to be compiled seamlessly on
edge/embedded systems without PyTorch installed.
"""

import json
from typing import Dict, List, Tuple, Optional, Any, Union
from .graph import Graph, Node
from .tensor import Tensor
from . import ops

# Common mapping from PyTorch target functions/names to Zen-NPU frontend op types
PYTORCH_OP_MAPPING = {
    # Matrix Multiplications
    "matmul": "matmul",
    "mm": "matmul",
    "bmm": "matmul",
    "torch.matmul": "matmul",
    "torch.mm": "matmul",
    "torch.bmm": "matmul",
    "aten.mm.default": "matmul",
    "aten.bmm.default": "matmul",
    "aten.matmul.default": "matmul",
    
    # Additions & Elementwise
    "add": "add",
    "__add__": "add",
    "torch.add": "add",
    "aten.add.Tensor": "add",
    "aten.add.default": "add",
    "operator.add": "add",

    # Multiplications
    "mul": "mul",
    "__mul__": "mul",
    "torch.mul": "mul",
    "aten.mul.Tensor": "mul",
    "aten.mul.default": "mul",
    "operator.mul": "mul",

    # Activations
    "relu": "relu",
    "torch.relu": "relu",
    "torch.nn.functional.relu": "relu",
    "aten.relu.default": "relu",

    "silu": "silu",
    "torch.nn.functional.silu": "silu",
    "aten.silu.default": "silu",

    "gelu": "gelu",
    "torch.nn.functional.gelu": "gelu",
    "aten.gelu.default": "gelu",

    # Normalization & Attention
    "layer_norm": "rmsnorm",
    "rms_norm": "rmsnorm",
    "torch.nn.functional.layer_norm": "rmsnorm",
    "aten.layer_norm.default": "rmsnorm",
    "softmax": "softmax",
    "torch.nn.functional.softmax": "softmax",
    "aten.softmax.default": "softmax",
}


class FXImporter:
    """
    Translates PyTorch FX Graph structures into Zen-NPU frontend.Graph.
    """
    def __init__(self, name: str = "PyTorch_Exported_Model"):
        self.name = name

    def from_fx_nodes(self, node_specs: List[Dict[str, Any]], tensor_meta: Optional[Dict[str, Dict[str, Any]]] = None) -> Graph:
        """
        Builds a Graph from structured node specifications.
        node_spec format:
        {
            "op": "placeholder" | "call_function" | "call_method" | "output",
            "name": "node_name",
            "target": "matmul" | "add" | ...,
            "args": ["input_x", "weight"],
            "shape": [32, 64],  # optional
            "dtype": "float32"   # optional
        }
        """
        graph = Graph(self.name)
        tensor_map: Dict[str, Tensor] = {}
        tensor_meta = tensor_meta or {}

        def _get_or_create_tensor(t_name: str, fallback_shape=(32, 32), fallback_dtype="float32") -> Tensor:
            if t_name not in tensor_map:
                meta = tensor_meta.get(t_name, {})
                shape = meta.get("shape", fallback_shape)
                dtype = meta.get("dtype", fallback_dtype)
                tensor_map[t_name] = Tensor(t_name, shape, dtype=dtype)
            return tensor_map[t_name]

        for spec in node_specs:
            op_kind = spec.get("op")
            node_name = spec.get("name")
            target = str(spec.get("target", ""))
            args = spec.get("args", [])
            shape = tuple(spec.get("shape", [32, 32]))
            dtype = spec.get("dtype", "float32")

            if op_kind == "placeholder":
                # Input argument tensor
                inp_tensor = _get_or_create_tensor(node_name, shape, dtype)
                graph.add_input(inp_tensor)

            elif op_kind in ("call_function", "call_method", "call_module"):
                # Lookup mapped op type
                mapped_op = self._resolve_op_type(target)
                input_tensors = []
                for arg in args:
                    if isinstance(arg, str):
                        input_tensors.append(_get_or_create_tensor(arg))

                out_tensor = _get_or_create_tensor(f"{node_name}_out", shape, dtype)
                node = Node(
                    name=node_name,
                    op_type=mapped_op,
                    inputs=input_tensors,
                    outputs=[out_tensor],
                    attrs=spec.get("attrs", {})
                )
                graph.add_node(node)

            elif op_kind == "output":
                # Output collection
                out_names = args if isinstance(args, list) else [args]
                outputs = []
                for out_name in out_names:
                    if isinstance(out_name, str):
                        outputs.append(_get_or_create_tensor(out_name))
                graph.set_outputs(outputs)

        return graph

    def from_json(self, json_content: Union[str, Dict[str, Any]]) -> Graph:
        """Parses a serialized JSON FX Graph dump."""
        data = json.loads(json_content) if isinstance(json_content, str) else json_content
        model_name = data.get("name", self.name)
        nodes = data.get("nodes", [])
        tensor_meta = data.get("tensor_meta", {})
        importer = FXImporter(name=model_name)
        return importer.from_fx_nodes(nodes, tensor_meta)

    def from_torch_module(self, module: Any, sample_inputs: Any) -> Graph:
        """
        Translates a live PyTorch nn.Module using torch.fx.symbolic_trace or torch.export.
        Only executed if torch is installed in the current environment.
        """
        try:
            import torch
            import torch.fx
        except ImportError:
            raise RuntimeError(
                "PyTorch is not installed in the current environment. "
                "Use FXImporter.from_json() to import pre-exported FX graphs without torch."
            )

        # Trace module to FX Graph
        traced_graph = torch.fx.symbolic_trace(module)
        return self.from_fx_graph(traced_graph, name=getattr(module, "__class__", type("Module")).__name__)

    def from_fx_graph(self, fx_graph: Any, name: Optional[str] = None) -> Graph:
        """Translates an in-memory torch.fx.Graph object."""
        node_specs = []
        tensor_meta = {}

        for node in fx_graph.nodes:
            spec = {
                "op": node.op,
                "name": node.name,
                "target": str(node.target),
                "args": [arg.name if hasattr(arg, "name") else str(arg) for arg in node.args],
                "attrs": {}
            }
            # Extract tensor metadata if annotated by Dynamo or ShapeEnv
            if hasattr(node, "meta") and "tensor_meta" in node.meta:
                tm = node.meta["tensor_meta"]
                spec["shape"] = list(tm.shape) if hasattr(tm, "shape") else [32, 32]
                spec["dtype"] = str(tm.dtype).replace("torch.", "") if hasattr(tm, "dtype") else "float32"
                tensor_meta[node.name] = {"shape": spec["shape"], "dtype": spec["dtype"]}

            node_specs.append(spec)

        importer = FXImporter(name=name or self.name)
        return importer.from_fx_nodes(node_specs, tensor_meta)

    def _resolve_op_type(self, target: str) -> str:
        """Resolves PyTorch function / method target to Zen-NPU operator."""
        clean_target = target.split(".")[-1]
        for key, val in PYTORCH_OP_MAPPING.items():
            if key in target or key == clean_target:
                return val
        # Default fallback
        return clean_target.lower()
