"""
Backend: LLVM RISC-V RV64 + Custom-0 NPU Instruction Emission.
Completely decoupled via OpRegistry (Open-Closed Principle):
- Integrates the Progressive Multi-Level IR Lowering Pipeline:
  Level 1: High-Level Graph IR (frontend.Graph)
  Level 2: Loop & Buffer IR (ir.LoopModule)
  Level 3: Command & HAL Runtime IR (ir.CommandModule)
  Level 4: Machine RISC-V RV64 Assembly / Freestanding C
Adding new models and new operators requires ZERO modifications to this file.
"""

from typing import List, Dict, Any
from compiler.frontend import Graph, OpNode, Tensor, OpRegistry, OpTrait
from compiler.midend.tvm_pipeline import TilingAndPipelinePass
from compiler.midend.flow_dispatch import FlowDispatchPass
from compiler.ir import lower_graph_to_loop_ir, lower_loop_ir_to_command_ir, LoopModule, CommandModule

class RiscvNpuCodeGenerator:
    def __init__(self, sram_bytes: int = 16 * 1024, num_cores: int = 4):
        self.sram_bytes = sram_bytes
        self.num_cores = num_cores
        self.tiler = TilingAndPipelinePass(sram_bytes)
        self.dispatcher = FlowDispatchPass(num_cores)

    def lower_to_loop_ir(self, graph: Graph, total_dram_bytes: int) -> LoopModule:
        """Lowers Level 1 Graph IR -> Level 2 Loop & Buffer IR (TIR)."""
        return lower_graph_to_loop_ir(graph, total_dram_bytes, self.sram_bytes, self.num_cores)

    def lower_to_command_ir(self, loop_mod: LoopModule, total_dram_bytes: int) -> CommandModule:
        """Lowers Level 2 Loop IR -> Level 3 Command & HAL Runtime IR."""
        return lower_loop_ir_to_command_ir(loop_mod, total_dram_bytes, self.sram_bytes, self.num_cores)

    def generate(self, graph: Graph, total_dram_bytes: int) -> str:
        lines: List[str] = []
        lines.append("// ============================================================================")
        lines.append(f"// Generated by AetherCompiler (Multi-Level IR Progressive Pipeline)")
        lines.append(f"// Target: {self.num_cores}-Core RISC-V 64-bit Core + NPU Custom-0 Coprocessor")
        lines.append("// ============================================================================\n")

        lines.append("// Freestanding definitions for zero-dependency compilation on RISC-V and Host")
        lines.append("#ifdef __riscv")
        lines.append("typedef unsigned long  size_t;")
        lines.append("typedef unsigned char  uint8_t;")
        lines.append("static inline void* npu_memset(void* s, int c, size_t n) {")
        lines.append("    unsigned char* p = (unsigned char*)s;")
        lines.append("    while (n--) *p++ = (unsigned char)c;")
        lines.append("    return s;")
        lines.append("}")
        lines.append("#define memset npu_memset")
        lines.append("#else")
        lines.append("#include <stdio.h>")
        lines.append("#include <stdlib.h>")
        lines.append("#include <string.h>")
        lines.append("#include <stdint.h>")
        lines.append("#include <math.h>")
        lines.append("#endif\n")

        lines.append(f"#define GLOBAL_DRAM_SIZE  {total_dram_bytes}")
        lines.append(f"#define PER_CORE_SRAM     {self.sram_bytes}")
        lines.append(f"#define NUM_NPU_CORES     {self.num_cores}\n")

        # Instruction wrappers
        lines.append("""
// --- NPU Custom-0 Coprocessor Instruction Wrappers & Host Fallback ---
#if defined(__riscv) && defined(__riscv_xlen) && (__riscv_xlen == 64)
// Hardware instructions in RISC-V custom-0 opcode (0x0B)
static inline void npu_dma_async(void* dst, const void* src, size_t bytes) {
    asm volatile (".insn r 0x0b, 0, 1, x0, %0, %1\\n" : : "r"(dst), "r"(src), "r"(bytes) : "memory");
}
static inline void npu_dma_wait(void) {
    asm volatile (".insn i 0x0b, 1, x0, x0, 0\\n" : : : "memory");
}
static inline void npu_matmul_tile(float* c, const float* a, const float* b, int bm, int bn, int bk, int lda, int ldb, int ldc) {
    asm volatile (".insn r 0x0b, 0, 2, %0, %1, %2\\n" : : "r"(c), "r"(a), "r"(b) : "memory");
}
static inline void npu_bias_relu_tile(float* c, const float* bias, int bm, int bn, int ldc) {
    asm volatile (".insn r 0x0b, 0, 3, %0, %1, %2\\n" : : "r"(c), "r"(bias), "r"((size_t)(bm * bn)) : "memory");
}
static inline void npu_rmsnorm_tile(float* out, const float* in, const float* weight, int tokens, int dim, float eps) {
    asm volatile (".insn r 0x0b, 0, 4, %0, %1, %2\\n" : : "r"(out), "r"(in), "r"(weight) : "memory");
}
static inline void npu_silu_mul_tile(float* out, const float* gate, const float* up, int tokens, int dim) {
    asm volatile (".insn r 0x0b, 0, 5, %0, %1, %2\\n" : : "r"(out), "r"(gate), "r"(up) : "memory");
}
static inline void npu_rope_tile(float* out, const float* in, const float* cos_tab, const float* sin_tab, int tokens, int dim) {
    asm volatile (".insn r 0x0b, 0, 6, %0, %1, %2\\n" : : "r"(out), "r"(in), "r"(cos_tab) : "memory");
}
static inline void npu_flash_attention_tile(float* out, const float* q, const float* k, const float* v, int tokens, int dim) {
    asm volatile (".insn r 0x0b, 0, 7, %0, %1, %2\\n" : : "r"(out), "r"(q), "r"(k) : "memory");
}
static inline void npu_dma_async_2d(void* dst, const void* src, int rows, int cols, int dst_stride, int src_stride, size_t elem_size) {
    if (cols == dst_stride && cols == src_stride) {
        npu_dma_async(dst, src, (size_t)rows * cols * elem_size);
    } else {
        for (int r = 0; r < rows; ++r) {
            npu_dma_async((char*)dst + r * dst_stride * elem_size, (const char*)src + r * src_stride * elem_size, (size_t)cols * elem_size);
        }
    }
}
#else
// C Host Emulation Reference (with 4-Way Loop Unrolling & Instruction-Level Parallelism)
static inline void npu_dma_async(void* dst, const void* src, size_t bytes) {
    memcpy(dst, src, bytes);
}
static inline void npu_dma_wait(void) {}
static inline void npu_dma_async_2d(void* dst, const void* src, int rows, int cols, int dst_stride, int src_stride, size_t elem_size) {
    if (cols == dst_stride && cols == src_stride) {
        memcpy(dst, src, (size_t)rows * cols * elem_size);
    } else {
        for (int r = 0; r < rows; ++r) {
            memcpy((char*)dst + r * dst_stride * elem_size, (const char*)src + r * src_stride * elem_size, (size_t)cols * elem_size);
        }
    }
}
static inline void npu_matmul_tile(float* c, const float* a, const float* b, int bm, int bn, int bk, int lda, int ldb, int ldc) {
    for (int i = 0; i < bm; ++i) {
        for (int j = 0; j < bn; ++j) {
            float sum0 = 0.0f;
            int k = 0;
            // 4-Way ILP Loop Unrolling along reduction dimension
            for (; k <= bk - 4; k += 4) {
                sum0 += a[i * lda + k + 0] * b[(k + 0) * ldb + j];
                sum0 += a[i * lda + k + 1] * b[(k + 1) * ldb + j];
                sum0 += a[i * lda + k + 2] * b[(k + 2) * ldb + j];
                sum0 += a[i * lda + k + 3] * b[(k + 3) * ldb + j];
            }
            for (; k < bk; ++k) {
                sum0 += a[i * lda + k] * b[k * ldb + j];
            }
            c[i * ldc + j] += sum0;
        }
    }
}
static inline void npu_bias_relu_tile(float* c, const float* bias, int bm, int bn, int ldc) {
    for (int i = 0; i < bm; ++i) {
        for (int j = 0; j < bn; ++j) {
            float v = c[i * ldc + j] + (bias ? bias[j] : 0.0f);
            c[i * ldc + j] = (v > 0.0f) ? v : 0.0f;
        }
    }
}
static inline void npu_rmsnorm_tile(float* out, const float* in, const float* weight, int tokens, int dim, float eps) {
    for (int t = 0; t < tokens; ++t) {
        float sum_sq = 0.0f;
        const float* in_ptr = &in[t * dim];
        int d = 0;
        // 4-Way Unrolled ILP Sum of Squares
        for (; d <= dim - 4; d += 4) {
            float v0 = in_ptr[d + 0];
            float v1 = in_ptr[d + 1];
            float v2 = in_ptr[d + 2];
            float v3 = in_ptr[d + 3];
            sum_sq += v0 * v0 + v1 * v1 + v2 * v2 + v3 * v3;
        }
        for (; d < dim; ++d) {
            float v = in_ptr[d];
            sum_sq += v * v;
        }
        float rms = 1.0f / (float)sqrt((double)(sum_sq / dim + eps));
        float* out_ptr = &out[t * dim];
        d = 0;
        for (; d <= dim - 4; d += 4) {
            out_ptr[d + 0] = in_ptr[d + 0] * rms * weight[d + 0];
            out_ptr[d + 1] = in_ptr[d + 1] * rms * weight[d + 1];
            out_ptr[d + 2] = in_ptr[d + 2] * rms * weight[d + 2];
            out_ptr[d + 3] = in_ptr[d + 3] * rms * weight[d + 3];
        }
        for (; d < dim; ++d) {
            out_ptr[d] = in_ptr[d] * rms * weight[d];
        }
    }
}
static inline void npu_silu_mul_tile(float* out, const float* gate, const float* up, int tokens, int dim) {
    int total = tokens * dim;
    int idx = 0;
    for (; idx <= total - 4; idx += 4) {
        for (int step = 0; step < 4; ++step) {
            int k = idx + step;
            float g = gate[k];
            float silu_val = g / (1.0f + (float)exp(-(double)g));
            out[k] = silu_val * up[k];
        }
    }
    for (; idx < total; ++idx) {
        float g = gate[idx];
        float silu_val = g / (1.0f + (float)exp(-(double)g));
        out[idx] = silu_val * up[idx];
    }
}
static inline void npu_rope_tile(float* out, const float* in, const float* cos_tab, const float* sin_tab, int tokens, int dim) {
    int half_dim = dim / 2;
    for (int t = 0; t < tokens; ++t) {
        for (int i = 0; i < half_dim; ++i) {
            float x1 = in[t * dim + i];
            float x2 = in[t * dim + i + half_dim];
            float c = cos_tab[t * dim + i];
            float s = sin_tab[t * dim + i];
            out[t * dim + i] = x1 * c - x2 * s;
            out[t * dim + i + half_dim] = x1 * s + x2 * c;
        }
    }
}
static inline void npu_flash_attention_tile(float* out, const float* q, const float* k, const float* v, int tokens, int dim) {
    float scale = 1.0f / (float)sqrt((double)dim);
    for (int i = 0; i < tokens; ++i) {
        float max_s = -1e9f;
        float sum_exp = 0.0f;
        float s_row[128];
        int num_j = (tokens < 128) ? tokens : 128;
        for (int j = 0; j < num_j; ++j) {
            float dot = 0.0f;
            for (int d = 0; d < dim; ++d) dot += q[i * dim + d] * k[j * dim + d];
            s_row[j] = dot * scale;
            if (s_row[j] > max_s) max_s = s_row[j];
        }
        for (int j = 0; j < num_j; ++j) {
            s_row[j] = (float)exp((double)(s_row[j] - max_s));
            sum_exp += s_row[j];
        }
        for (int d = 0; d < dim; ++d) {
            float acc = 0.0f;
            for (int j = 0; j < num_j; ++j) acc += (s_row[j] / sum_exp) * v[j * dim + d];
            out[i * dim + d] = acc;
        }
    }
}
#endif
""")

        lines.append("// Multi-Core Entry Point: dispatches across available NPU cores")
        lines.append("void run_model(uint8_t* dram_base, int core_id) {\n")

        for node_idx, node in enumerate(graph.nodes):
            op_def = OpRegistry.get(node.op_type)

            lines.append(f"    // ==================================================================")
            lines.append(f"    // Step {node_idx + 1}: Node '{node.name}' (Op: {node.op_type})")
            lines.append(f"    // ==================================================================")
            lines.append("    {")

            # Check if this operator is a dense MatMul contraction (benefits from TVM Scratchpad Tiling)
            if OpTrait.MATMUL_LIKE in op_def.traits and node.op_type in ("matmul", "fused_matmul_add_relu", "fused_matmul_add"):
                X = node.inputs[0]
                W = node.inputs[1]
                B = node.inputs[2] if len(node.inputs) > 2 else None
                Y = node.outputs[0]

                M, K = X.shape[-2], X.shape[-1]
                N = W.shape[-1]
                sched = self.tiler.schedule(M, N, K)
                BM, BN, BK = sched.BM, sched.BN, sched.BK

                lines.append(f"        // Tensor Offsets in Global DRAM")
                lines.append(f"        float* dev_X = (float*)(dram_base + {X.allocated_offset});")
                lines.append(f"        float* dev_W = (float*)(dram_base + {W.allocated_offset});")
                if B:
                    lines.append(f"        float* dev_B = (float*)(dram_base + {B.allocated_offset});")
                lines.append(f"        float* dev_Y = (float*)(dram_base + {Y.allocated_offset});\n")

                lines.append(f"        // On-chip SRAM Double Buffering (TVM TensorIR 2-Stage Pipeline)")
                lines.append(f"        static float sram_a[2][{BM} * {BK}];")
                lines.append(f"        static float sram_b[2][{BK} * {BN}];")
                lines.append(f"        static float sram_c[{BM} * {BN}];")
                if B:
                    lines.append(f"        static float sram_bias[{BN}];")

                # Adaptive Multi-Core Partitioning:
                # If M is concrete and M < NUM_NPU_CORES (e.g. Decode phase M=1), partition across N columns!
                is_decode_mode = isinstance(M, int) and (M < self.num_cores)

                if is_decode_mode:
                    lines.append(f"\n        // IREE Flow Adaptive Partitioning: Decode Phase (M={M} < {self.num_cores} cores) -> Partition along N columns")
                    lines.append(f"        int chunk_n = ({N} + NUM_NPU_CORES - 1) / NUM_NPU_CORES;")
                    lines.append(f"        int n_start = core_id * chunk_n;")
                    lines.append(f"        int n_end   = (n_start + chunk_n < {N}) ? (n_start + chunk_n) : {N};")
                    lines.append(f"        int m_start = 0;")
                    lines.append(f"        int m_end   = {M};\n")
                else:
                    lines.append(f"\n        // IREE Flow Adaptive Partitioning: Prefill/Batch Phase -> Partition along M rows")
                    lines.append(f"        int chunk_m = ({M} + NUM_NPU_CORES - 1) / NUM_NPU_CORES;")
                    lines.append(f"        int m_start = core_id * chunk_m;")
                    lines.append(f"        int m_end   = (m_start + chunk_m < {M}) ? (m_start + chunk_m) : {M};")
                    lines.append(f"        int n_start = 0;")
                    lines.append(f"        int n_end   = {N};\n")

                lines.append(f"        for (int m = m_start; m < m_end; m += {BM}) {{")
                lines.append(f"            int actual_bm = (m + {BM} <= m_end) ? {BM} : (m_end - m);")
                lines.append(f"            for (int n = n_start; n < n_end; n += {BN}) {{")
                lines.append(f"                int actual_bn = (n + {BN} <= n_end) ? {BN} : (n_end - n);")
                lines.append(f"                memset(sram_c, 0, sizeof(sram_c));")
                if B:
                    lines.append(f"                npu_dma_async(sram_bias, &dev_B[n], actual_bn * sizeof(float));")
                    lines.append(f"                npu_dma_wait();")

                lines.append(f"                int p = 0; // Ping-pong index")
                lines.append(f"                int init_bk = ({K} < {BK}) ? {K} : {BK};")
                lines.append(f"                // 1. Prefetch Stage 0 Tile (Boundary Safe 2D DMA)")
                lines.append(f"                npu_dma_async_2d(sram_a[p], &dev_X[m * {K} + 0], actual_bm, init_bk, {BK}, {K}, sizeof(float));")
                lines.append(f"                npu_dma_async_2d(sram_b[p], &dev_W[0 * {N} + n], init_bk, actual_bn, {BN}, {N}, sizeof(float));\n")

                lines.append(f"                for (int k = 0; k < {K}; k += {BK}) {{")
                lines.append(f"                    npu_dma_wait(); // Wait for tile [p]")
                lines.append(f"                    int next_p = 1 - p;")
                lines.append(f"                    int actual_bk = (k + {BK} <= {K}) ? {BK} : ({K} - k);")
                lines.append(f"                    if (k + {BK} < {K}) {{")
                lines.append(f"                        int next_bk = (k + 2 * {BK} <= {K}) ? {BK} : ({K} - (k + {BK}));")
                lines.append(f"                        // 2. Overlap DMA for next tile [next_p]")
                lines.append(f"                        npu_dma_async_2d(sram_a[next_p], &dev_X[m * {K} + (k + {BK})], actual_bm, next_bk, {BK}, {K}, sizeof(float));")
                lines.append(f"                        npu_dma_async_2d(sram_b[next_p], &dev_W[(k + {BK}) * {N} + n], next_bk, actual_bn, {BN}, {N}, sizeof(float));")
                lines.append(f"                    }}")
                lines.append(f"                    // 3. Matrix Coprocessor Tile Compute")
                lines.append(f"                    npu_matmul_tile(sram_c, sram_a[p], sram_b[p], actual_bm, actual_bn, actual_bk, {BK}, {BN}, {BN});")
                lines.append(f"                    p = next_p;")
                lines.append(f"                }}\n")

                if node.op_type == "fused_matmul_add_relu":
                    lines.append(f"                // 4. Fused Epilogue: Bias Add + ReLU in-place on SRAM")
                    lines.append(f"                npu_bias_relu_tile(sram_c, sram_bias, actual_bm, actual_bn, {BN});")

                lines.append(f"                // 5. Store result back to Global DRAM via DMA (Boundary Safe 2D DMA)")
                lines.append(f"                npu_dma_async_2d(&dev_Y[m * {N} + n], sram_c, actual_bm, actual_bn, {N}, {BN}, sizeof(float));")
                lines.append(f"                npu_dma_wait();")
                lines.append(f"            }}")
                lines.append(f"        }}")
            else:
                # Decoupled emission: delegates directly to registered OpDefinition!
                ctx = {"dram_base": "dram_base", "core_id": "core_id"}
                emitted_lines = op_def.emit_c(node, ctx)
                lines.extend(emitted_lines)

            lines.append("    }\n")

        lines.append("}\n")
        return "\n".join(lines)
