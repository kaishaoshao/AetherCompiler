"""
Backend: MLIR 3-Dialect Exporter (Python Graph -> Authentic Aether MLIR Assembly).

Bridges `feat/learn` Python Graphs directly to the 3 LLVM/MLIR TableGen dialects in `mlir/`:
  - `aether_graph.*` : High-level LLM macro-ops (matmul, rmsnorm, swiglu, attention, paged_attention, moe_router, custom_kernel)
  - `aether_mem.*`   : Explicit storage-tier transfers & `#aether_mem.space<"tier">` encodings
  - `aether_place.*` : Explicit placement & collective ops (`#aether_place.spec<chip=..., tp=...>`, `all_reduce`)
"""

from typing import List
from compiler.frontend import Graph, OpNode, Tensor


_DTYPE_TO_MLIR = {
    "float32": "f32",
    "float16": "f16",
    "bfloat16": "bf16",
    "fp8_e4m3": "f8E4M3FN",
    "fp8_e5m2": "f8E5M2",
    "int32": "i32",
    "int16": "i16",
    "int8": "i8",
    "int4": "i4",
    "bool": "i1",
}

_MEM_OPS = {"dma_transfer", "tier_offload", "tier_prefetch"}
_PLACE_OPS = {"all_reduce"}


def format_mlir_tensor_type(t: Tensor) -> str:
    dims = "x".join("?" if not isinstance(d, int) else str(d) for d in t.shape)
    dt = _DTYPE_TO_MLIR.get(t.dtype, "f32")
    mem = t.attrs.get("storage_tier", "3D_DRAM_Stack_Tier")
    return f'tensor<{dims}x{dt}, #aether_mem.space<"{mem}">>'


def export_graph_to_aether_mlir(graph: Graph) -> str:
    """Emits valid multi-dialect MLIR assembly targeting `mlir/include/Aether/Dialect/*`."""
    lines: List[str] = [
        f"// Generated by AetherCompiler MLIRExporter (aether_graph + aether_mem + aether_place)",
        f"module @{graph.name} {{",
    ]
    args = ", ".join(f"%{t.name}: {format_mlir_tensor_type(t)}" for t in graph.inputs)
    rets = ", ".join(format_mlir_tensor_type(t) for t in graph.outputs)
    lines.append(f"  func.func @forward({args}) -> ({rets}) {{")

    for node in graph.nodes:
        inps = ", ".join(f"%{t.name}" for t in node.inputs)
        in_types = ", ".join(format_mlir_tensor_type(t) for t in node.inputs)
        out_names = ", ".join(f"%{t.name}" for t in node.outputs)
        out_types = ", ".join(format_mlir_tensor_type(t) for t in node.outputs)

        if node.op_type in _MEM_OPS:
            op_full = f"aether_mem.{node.op_type}"
        elif node.op_type in _PLACE_OPS:
            op_full = f"aether_place.{node.op_type}"
        elif node.op_type.startswith("custom_"):
            op_full = "aether_graph.custom_kernel"
        elif node.op_type == "fused_silu_mul":
            op_full = "aether_graph.swiglu"
        else:
            op_full = f"aether_graph.{node.op_type}"

        attr_parts: List[str] = []
        chip = node.get_placement_chip() if hasattr(node, "get_placement_chip") else node.attrs.get("placement")
        if chip is None and op_full.startswith("aether_graph."):
            chip = "systolic_npu_die"
        ws = node.get_tp_world_size() if hasattr(node, "get_tp_world_size") else int(node.attrs.get("tp_world_size", 1))
        if chip:
            attr_parts.append(f'placement = #aether_place.spec<chip = "{chip}", tp = {ws}>')
        if node.op_type in _MEM_OPS:
            src_t = node.attrs.get("src_tier", "3D_DRAM_Stack_Tier")
            dst_t = node.attrs.get("dst_tier", "NPU_Local_Scratchpad_SRAM")
            attr_parts.append(f'src_tier = "{src_t}", dst_tier = "{dst_t}"')
        if node.op_type.startswith("custom_"):
            fw = node.attrs.get("framework", "triton")
            attr_parts.append(f'framework = "{fw}", symbol = "@{node.op_type}"')
        if "eps" in node.attrs:
            attr_parts.append(f"eps = {float(node.attrs['eps']):.1e} : f32")
        if "top_k" in node.attrs:
            attr_parts.append(f"top_k = {int(node.attrs['top_k'])} : i64")

        attr_str = f" {{{', '.join(attr_parts)}}}" if attr_parts else ""
        lines.append(f"    {out_names} = {op_full}({inps}){attr_str} : ({in_types}) -> ({out_types})")

    ret_vals = ", ".join(f"%{t.name}" for t in graph.outputs)
    lines.append(f"    return {ret_vals} : {rets}")
    lines.append("  }")
    lines.append("}")
    return "\n".join(lines)
